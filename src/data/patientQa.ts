const normalizeQuestion = (text: string) => text
  .normalize('NFKC')
  .toLowerCase()
  .replace(/[\s，。！？、；：,.!?;:'"“”‘’（）()《》【】]+/g, '')

/** 仅按明确配置的词组匹配，避免用模糊相似度误答医疗问题。 */
export function matchPatientQa(input: string, presets: PresetQA[]): PresetQA | null {
  const text = normalizeQuestion(input)
  const exact = presets.find((item) => normalizeQuestion(item.question) === text)
  if (exact) return exact

  const matches = presets.filter((item) => item.matchTerms?.some((group) =>
    group.every((term) => text.includes(normalizeQuestion(term))),
  ))
  return matches.length === 1 ? matches[0] : null
}

